"""fix/sync-config-regenerates-tools-md

PR #785 removed a dead "Complete phase" route from
app/services/tools_md_builder.py — but POST /agents/{id}/sync-config writes
TOOLS.md "from DB" (docker_agent_sync.sync_docker_agent_files step 4 /
sync_host_agent_files step 4): it only mirrors the already-stored
agent.tools_md into the file, it never re-runs the builder. Live-verified
12.10.2026: existing agents still carry the dead route in TOOLS.md after a
sync-config call, because nothing regenerates agent.tools_md from the
builder before it gets mirrored to disk.

Fix: sync_agent_config_to_gateway() (the sync-config endpoint) regenerates
agent.tools_md from generate_tools_md() first, using the agent's current
name/emoji/board/is_board_lead/scopes/runtime/comm_v2 — mirroring how SOUL.md
is already always re-rendered on every sync-config (ADR-006, "templates are
the source"). TOOLS.md gets the same treatment: operator edits via
PUT .../config/tools_md are intentionally not "sticky" across a sync-config,
exactly like soul_md already behaves.

Token note (verified live in app/services/tools_md_builder.py): since commit
d1a4884c ("replace hardcoded token with $MC_AGENT_TOKEN"), generate_tools_md's
output never embeds a literal bearer token — every curl example uses the
$MC_AGENT_TOKEN placeholder, resolved at runtime from the agent's own
environment. The real secret lives in the vault (`mc_token_{slug}`,
app/services/secrets_helper.py) and in agent.agent_token_hash — neither is
touched by tools_md regeneration. "Never mint a new token" therefore means:
this fix must not call generate_agent_token()/reset-token and must not change
agent.agent_token_hash or the vault secret — asserted directly below, which is
the behavior that actually matters (grepping for a literal token in the
builder's own output would be a false signal: it's never there, regenerated
or not).
"""
from __future__ import annotations

import uuid

import pytest
from sqlmodel.ext.asyncio.session import AsyncSession

from app.models.agent import Agent
from app.routers.agents import sync_agent_config_to_gateway
from app.services.tools_md_builder import generate_tools_md

OLD_DEAD_ROUTE = "agent/phases/{phase_id}/complete"
NEW_TEXT = "Phase completion is operator-only"


def _stale_tools_md(name: str, emoji: str, board_id: str) -> str:
    """A TOOLS.md generated by an OLDER builder version that still taught
    the dead /phases/{id}/complete route PR #785 removed — simulating an
    agent that was created/reset before that fix shipped and never had its
    stored copy regenerated since."""
    current = generate_tools_md(name, emoji, "unused-placeholder-token", board_id, scopes=[])
    assert NEW_TEXT in current, "fixture assumption: current builder output has the new text"
    assert OLD_DEAD_ROUTE not in current, "fixture assumption: current builder has no dead route"
    old_block = (
        f"{NEW_TEXT} — there is no agent endpoint for it. Once\n"
        "ALL tasks of a phase are `done`, tell the operator so they can complete it."
    )
    assert old_block in current, "fixture assumption: unexpected builder prose, update the fixture"
    new_block = (
        "## Complete phase\n\n```\n"
        f'curl -s -X POST "$MC_API_URL/api/v1/{OLD_DEAD_ROUTE}" \\\n'
        '  -H "Authorization: Bearer $MC_AGENT_TOKEN"\n```\n\n'
        "Only call this once ALL tasks of the phase are `done`."
    )
    stale = current.replace(old_block, new_block)
    assert OLD_DEAD_ROUTE in stale, "fixture setup failed to inject the dead route"
    return stale


@pytest.fixture
def tmp_agent_dir(tmp_path, monkeypatch):
    import app.services.docker_agent_sync as sync_mod

    monkeypatch.setattr(sync_mod, "AGENTS_DIR", tmp_path)
    return tmp_path


async def _make_stale_cli_bridge_agent(session: AsyncSession) -> Agent:
    board_id = str(uuid.uuid4())
    agent = Agent(
        name="Cody",
        emoji="🧑‍💻",
        role="developer",
        agent_runtime="cli-bridge",
        board_id=uuid.UUID(board_id),
        is_board_lead=False,
        scopes=[],
        soul_md="x" * 1200,  # long enough to pass the settings.json guard, unused here
        tools_md=_stale_tools_md("Cody", "🧑‍💻", board_id),
        agent_token_hash="existing-hash-must-survive",
    )
    session.add(agent)
    await session.commit()
    await session.refresh(agent)
    return agent


@pytest.mark.asyncio
async def test_sync_config_regenerates_stale_tools_md_from_builder(async_session, tmp_agent_dir):
    agent = await _make_stale_cli_bridge_agent(async_session)

    # cli-bridge sync writes into AGENTS_DIR/<slug>/claude-config/ — the dir
    # must exist (sync_docker_agent_files bails out early otherwise).
    from app.services.docker_agent_sync import _agent_slug
    claude_dir = tmp_agent_dir / _agent_slug(agent) / "claude-config"
    claude_dir.mkdir(parents=True)

    await sync_agent_config_to_gateway(
        agent_id=agent.id,
        payload=None,
        restart=False,
        session=async_session,
        current_user=None,
    )

    await async_session.refresh(agent)

    # The dead route must be gone from BOTH the DB copy and the file
    # sync_docker_agent_files actually writes to disk.
    assert OLD_DEAD_ROUTE not in agent.tools_md, (
        "sync-config did not regenerate the stale TOOLS.md from the builder"
    )
    assert NEW_TEXT in agent.tools_md

    tools_file = claude_dir / "TOOLS.md"
    assert tools_file.exists()
    file_content = tools_file.read_text()
    assert OLD_DEAD_ROUTE not in file_content
    assert NEW_TEXT in file_content


@pytest.mark.asyncio
async def test_sync_config_never_mints_a_new_token(async_session, tmp_agent_dir, monkeypatch):
    """Sabotage probe: regenerating TOOLS.md must not touch the real token
    machinery (agent_token_hash / the vault secret). If the fix accidentally
    called generate_agent_token()/reset-token-style logic, agent_token_hash
    would change and generate_agent_token would be invoked — both asserted
    against directly, since the builder's own output never carries a literal
    token to begin with (see module docstring)."""
    import app.auth as auth_mod

    called = {"n": 0}
    real_generate = auth_mod.generate_agent_token

    def _spy(*a, **kw):
        called["n"] += 1
        return real_generate(*a, **kw)

    monkeypatch.setattr(auth_mod, "generate_agent_token", _spy)

    agent = await _make_stale_cli_bridge_agent(async_session)
    original_hash = agent.agent_token_hash

    from app.services.docker_agent_sync import _agent_slug
    claude_dir = tmp_agent_dir / _agent_slug(agent) / "claude-config"
    claude_dir.mkdir(parents=True)

    await sync_agent_config_to_gateway(
        agent_id=agent.id, payload=None, restart=False, session=async_session, current_user=None,
    )
    await async_session.refresh(agent)

    assert called["n"] == 0, "sync-config minted a new agent token — it must only extract/reuse"
    assert agent.agent_token_hash == original_hash, "sync-config must never rotate the token hash"
